#!/usr/bin/env python3
#
# Generate kernel/ksymtab.c, the symbol + line tables for backtrace().
#
#   mksyms.py kernel.nm kernel.lines  -> real tables
#
# kernel.nm    = output of `nm -n kernel/kernel`
# kernel.lines = output of `objdump --dwarf=decodedline kernel/kernel`
#
import re
import sys

def emit(funcs, lines, files):
    out = ['// generated by kernel/mksyms.py -- do not edit',
           '#include "types.h"',
           '#include "ksym.h"',
           '']
    out.append('const int ksym_nfuncs = %d;' % len(funcs))
    out.append('const struct ksym_func ksym_funcs[] = {')
    for addr, name in funcs:
        out.append('  {0x%x, "%s"},' % (addr, name))
    if not funcs:
        out.append('  {0, 0},')
    out.append('};')
    out.append('')
    out.append('const char *const ksym_files[] = {')
    for f in files:
        out.append('  "%s",' % f)
    if not files:
        out.append('  0,')
    out.append('};')
    out.append('')
    out.append('const int ksym_nlines = %d;' % len(lines))
    out.append('const struct ksym_line ksym_lines[] = {')
    for addr, line, fi in lines:
        out.append('  {0x%x, %d, %d},' % (addr, line, fi))
    if not lines:
        out.append('  {0, 0, 0},')
    out.append('};')
    print('\n'.join(out))

def read_funcs(path):
    funcs = {}
    for l in open(path):
        parts = l.split()
        # "<addr> <type> <name>"; T/t = code (text) symbols
        if len(parts) != 3 or parts[1] not in ('T', 't'):
            continue
        name = parts[2]
        if name.startswith('$') or name.startswith('.L'):
            continue
        addr = int(parts[0], 16)
        funcs.setdefault(addr, name)
    return sorted(funcs.items())

ROW = re.compile(r'^(\S+)\s+(\d+)\s+(0x[0-9a-fA-F]+)\b')

def read_lines(path):
    files, fileidx, rows = [], {}, {}
    for l in open(path):
        m = ROW.match(l)
        if not m:
            continue
        fname, line, addr = m.group(1), int(m.group(2)), int(m.group(3), 16)
        if fname not in fileidx:
            fileidx[fname] = len(files)
            files.append(fname)
        rows[addr] = (line, fileidx[fname])
    lines = []
    for addr in sorted(rows):
        line, fi = rows[addr]
        if lines and lines[-1][1:] == (line, fi):
            continue
        lines.append((addr, line, fi))
    return lines, files

if __name__ == '__main__':
    if len(sys.argv) != 3:
        sys.exit('usage: mksyms.py kernel.nm kernel.lines')
    lines, files = read_lines(sys.argv[2])
    emit(read_funcs(sys.argv[1]), lines, files)